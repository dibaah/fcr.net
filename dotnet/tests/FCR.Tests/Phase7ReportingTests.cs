using System.Net;
using System.Net.Http.Json;
using System.Text.Json;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Extensions.Configuration;
using Xunit;

namespace FCR.Tests;

public sealed class Phase7ReportingTests : IClassFixture<Phase7ReportingTests.Fixture>, IAsyncLifetime
{
    public sealed class Fixture : WebApplicationFactory<Program>
    {
        public string DataDir = Path.Combine(Path.GetTempPath(), $"fcr_phase7_{Guid.NewGuid():N}");
        public Fixture()
        {
            Directory.CreateDirectory(DataDir);
            foreach (var ext in new[] { "", "-wal", "-shm" })
            {
                var src = TestDb.RepoDbPath + ext;
                if (File.Exists(src)) File.Copy(src, Path.Combine(DataDir, "fcr_database.db" + ext));
            }
        }
        protected override void ConfigureWebHost(Microsoft.AspNetCore.Hosting.IWebHostBuilder builder) =>
            builder.ConfigureAppConfiguration((_, c) => c.AddInMemoryCollection(new Dictionary<string, string?>
            {
                ["FCR_DATA_DIR"] = DataDir,
                ["FCR_STATIC_DIR"] = ApiParityTests.Fixture.RepoStaticDir,
            }));
    }

    private readonly HttpClient _client;
    public Phase7ReportingTests(Fixture fixture) => _client = fixture.CreateClient();

    public async Task InitializeAsync()
    {
        var login = await _client.PostAsJsonAsync("/api/auth/login",
            new Dictionary<string, object?> { ["username"] = "admin", ["password"] = "admin" });
        login.EnsureSuccessStatusCode();
    }
    public Task DisposeAsync() => Task.CompletedTask;

    [Fact]
    public async Task AdminReports_AreAvailableAndReturnStructuredData()
    {
        var summary = await _client.GetAsync("/api/admin/reports/workflow-summary");
        Assert.Equal(HttpStatusCode.OK, summary.StatusCode);
        using var json = JsonDocument.Parse(await summary.Content.ReadAsStringAsync());
        Assert.True(json.RootElement.TryGetProperty("request_status_counts", out _));
        Assert.True(json.RootElement.TryGetProperty("workflow_status_counts", out _));

        Assert.Equal(HttpStatusCode.OK, (await _client.GetAsync("/api/admin/reports/approval-statistics")).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await _client.GetAsync("/api/admin/reports/pending-reviews")).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await _client.GetAsync("/api/admin/reports/review-aging")).StatusCode);
        Assert.Equal(HttpStatusCode.OK, (await _client.GetAsync("/api/admin/reports/user-activity")).StatusCode);
    }

    [Fact]
    public async Task MutatingRequest_IsRecordedInAuditActivity()
    {
        var create = await _client.PostAsJsonAsync("/api/requests/",
            new Dictionary<string, object?>
            {
                ["subject"] = "Phase 7 audit test",
                ["justification"] = "Verify the audit trail",
                ["description"] = "Test-only request generated by automated CI."
            });
        Assert.Equal(HttpStatusCode.Created, create.StatusCode);

        var activity = await _client.GetAsync("/api/admin/reports/user-activity?limit=20");
        Assert.Equal(HttpStatusCode.OK, activity.StatusCode);
        using var json = JsonDocument.Parse(await activity.Content.ReadAsStringAsync());
        var found = json.RootElement.EnumerateArray().Any(x =>
            x.GetProperty("path").GetString()!.StartsWith("/api/requests", StringComparison.Ordinal)
            && x.GetProperty("http_method").GetString() == "POST");
        Assert.True(found, "Expected POST /api/requests to appear in audit activity.");
    }

    [Fact]
    public async Task ReportsPage_IsServed()
    {
        var page = await _client.GetAsync("/phase7-reports.html");
        Assert.Equal(HttpStatusCode.OK, page.StatusCode);
        Assert.Contains("FCR Workflow Reports", await page.Content.ReadAsStringAsync());
    }
}
